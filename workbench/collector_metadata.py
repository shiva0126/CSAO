def enabled_collector_keys(config: Dict[str, Any]) -> List[str]:
    modules = config.get("modules", {}) or {}
    return [key for key, value in modules.items() if value and key in COLLECTOR_METADATA]


def collector_metadata_rows(config: Dict[str, Any] | None = None) -> List[Dict[str, Any]]:
    enabled = set(enabled_collector_keys(config or {})) if config is not None else None
    rows = []
    for key, item in COLLECTOR_METADATA.items():
        row = {"key": key, **item}
        row["enabled"] = enabled is None or key in enabled
        rows.append(row)
    return rows
