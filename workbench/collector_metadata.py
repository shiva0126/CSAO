from typing import Any, Dict, List


def perm(
    service: str,
    apis: List[str],
    actions: List[str],
    evidence: List[str],
    capability: str,
    classification: str = "required",
    purpose: str = "",
) -> Dict[str, Any]:
    return {
        "service": service,
        "apis": apis,
        "actions": actions,
        "classification": classification,
        "evidence": evidence,
        "capability": capability,
        "purpose": purpose or capability,
    }


